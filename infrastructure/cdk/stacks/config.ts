import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import type { App } from 'aws-cdk-lib'

export interface StageConfig {
  stage: string
  region: string
  allowedOrigins: string[]
  logRetentionDays: number
  removalPolicy: 'destroy' | 'retain'
  apiThrottling: {
    rateLimit: number
    burstLimit: number
  }
  existingLambdaRoleArn?: string
  openSearch: {
    minIndexingOcu: number
    maxIndexingOcu: number
    minSearchOcu: number
    maxSearchOcu: number
    standbyReplicas: 'ENABLED' | 'DISABLED'
  }
}

export function loadStageConfig(app: App): StageConfig {
  const stage = String(app.node.tryGetContext('stage') ?? process.env.STAGE ?? 'dev')
  if (!/^[a-z][a-z0-9-]{1,15}$/.test(stage)) throw new Error(`Invalid stage: ${stage}`)
  const currentDir = path.dirname(fileURLToPath(import.meta.url))
  const configPath = path.resolve(currentDir, '../../../config', `${stage}.json`)
  if (!fs.existsSync(configPath)) throw new Error(`Missing stage configuration: ${configPath}`)
  const config = JSON.parse(fs.readFileSync(configPath, 'utf8')) as StageConfig
  if (config.stage !== stage) throw new Error(`Stage mismatch in ${configPath}: expected ${stage}, received ${config.stage}`)
  if (!Array.isArray(config.allowedOrigins) || config.allowedOrigins.length !== 0) {
    throw new Error(`allowedOrigins in ${configPath} must be empty; the CloudFront origin is generated by CDK`)
  }
  if (!Number.isFinite(config.apiThrottling?.rateLimit) || config.apiThrottling.rateLimit <= 0 ||
      !Number.isInteger(config.apiThrottling?.burstLimit) || config.apiThrottling.burstLimit <= 0) {
    throw new Error(`apiThrottling in ${configPath} must define positive rateLimit and burstLimit values`)
  }
  if (config.apiThrottling.burstLimit < config.apiThrottling.rateLimit) {
    throw new Error(`apiThrottling.burstLimit must be greater than or equal to rateLimit in ${configPath}`)
  }
  const roleFromEnvironment = process.env.LAB_ROLE_ARN
  return { ...config, stage, existingLambdaRoleArn: roleFromEnvironment ?? config.existingLambdaRoleArn }
}

export function stackPrefix(config: StageConfig): string {
  return `CloudLearning-${config.stage}`
}
